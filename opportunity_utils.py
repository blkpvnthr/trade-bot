def get_data_tag() -> str:
    """
    Resolve DATA_TAG matching the pattern used in all existing modules.

    Order of precedence:
    1. RUN_DATA_DATE env var
    2. RL_DATA_DATE env var
    3. Today's date in ET as YYYYMMDD

    Returns
    -------
    str
        Data tag in format YYYYMMDD (e.g., "20260523")
    """
    tag = os.getenv("RUN_DATA_DATE") or os.getenv("RL_DATA_DATE")
    if tag:
        return tag
    return datetime.now(ET).strftime("%Y%m%d")


