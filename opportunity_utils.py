# Type Coercion
# ─────────────────────────────────────────────────────────────────────────────


def _json_default(obj: Any) -> Any:
    """JSON serialization fallback for NaN/Inf/datetime."""
    if isinstance(obj, float):
        if math.isnan(obj) or math.isinf(obj):
            return None
    if hasattr(obj, "isoformat"):
        return obj.isoformat()
    raise TypeError(f"Not JSON serializable: {type(obj)}")


def to_float(val: Any, default: float = 0.0) -> float:
    """
    Coerce value to float, returning default on NaN, Inf, None, or error.

    Parameters
    ----------
    val : Any
        Value to coerce
    default : float
        Default value to return on failure

    Returns
    -------
    float
        Coerced value or default.
    """
    try:
        v = float(val)
        return default if (math.isnan(v) or math.isinf(v)) else v
    except (TypeError, ValueError):
        return default


def to_int(val: Any, default: int = 0) -> int:
    """Coerce value to int, returning default on error."""
    try:
        return int(float(val))
    except (TypeError, ValueError):
        return default


def clip01(v: float) -> float:
    """Clip value to [0.0, 1.0]."""
    return max(0.0, min(1.0, v))


