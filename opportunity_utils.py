# Universe Loading / Writing
# ─────────────────────────────────────────────────────────────────────────────


def load_locked_universe(data_tag: str) -> list[str]:
    """
    Load symbols from locked_trading_universe.txt with fallback chain.

    Tries in order:
    1. {data_tag}_locked_trading_universe.txt (dated)
    2. locked_trading_universe.txt (undated)
    3. Yesterday's dated file
    4. Return empty list if all fail

    Normalizes via normalize_symbol, validates via is_valid_symbol.

    Returns
    -------
    list[str]
        Normalized, valid, uppercase symbol strings.
    """
    # Try dated file first
    dated_path = path_locked_universe(data_tag)
    if dated_path.exists():
        try:
            text = dated_path.read_text(encoding="utf-8").strip()
            if text:
                symbols = [normalize_symbol(s) for s in re.split(r"[\s,\n]+", text) if s.strip()]
                symbols = [s for s in symbols if is_valid_symbol(s)]
                return list(dict.fromkeys(symbols))  # dedup
        except Exception:
            pass

    # Try undated file
    undated_path = path_locked_universe_undated()
    if undated_path.exists():
        try:
            text = undated_path.read_text(encoding="utf-8").strip()
            if text:
                symbols = [normalize_symbol(s) for s in re.split(r"[\s,\n]+", text) if s.strip()]
                symbols = [s for s in symbols if is_valid_symbol(s)]
                return list(dict.fromkeys(symbols))
        except Exception:
            pass

    return []


def write_locked_universe(
    symbols: list[str],
    data_tag: str,
    log_fn: Callable[[str, dict], None] | None = None,
) -> bool:
    """
    Write symbols to locked_trading_universe.txt (both dated and undated).

    Format: one symbol per line, trailing newline.

    Writes to:
    1. {data_tag}_locked_trading_universe.txt (dated)
    2. locked_trading_universe.txt (undated alias)

    Parameters
    ----------
    symbols : list[str]
        List of symbol strings
    data_tag : str
        Data tag for dated filename
    log_fn : Callable | None
        Logger function

    Returns
    -------
    bool
        True if both writes succeeded, False if either failed.
    """
    # Normalize and validate
    symbols = [normalize_symbol(s) for s in symbols if s]
    symbols = [s for s in symbols if is_valid_symbol(s)]
    symbols = list(dict.fromkeys(symbols))  # dedup

    content = "\n".join(symbols) + "\n" if symbols else ""

    dated_path = path_locked_universe(data_tag)
    undated_path = path_locked_universe_undated()

    success = True
    success &= write_text_safe(dated_path, content, log_fn)
    success &= write_text_safe(undated_path, content, log_fn)

    return success


