# Symbol Normalization & Validation
# ─────────────────────────────────────────────────────────────────────────────


def normalize_symbol(val: Any) -> str:
    """
    Normalize symbol string: uppercase, strip whitespace, remove exchange prefix.

    E.g., "EXCHANGE:AAPL" → "AAPL", "aapl" → "AAPL".

    Parameters
    ----------
    val : Any
        Value to normalize

    Returns
    -------
    str
        Normalized symbol (may be invalid, check with is_valid_symbol)
    """
    s = str(val or "").upper().strip().replace(".", "-")
    # Strip "EXCHANGE:SYMBOL" prefix if present
    if ":" in s:
        s = s.split(":")[-1]
    return s


def is_valid_symbol(s: str) -> bool:
    """
    Check if symbol is valid: 1-10 chars, starts with letter, contains only A-Z and 0-9 and -.

    Pattern: r'[A-Z][A-Z0-9-]{0,9}'

    Parameters
    ----------
    s : str
        Symbol to validate

    Returns
    -------
    bool
        True if valid, False otherwise.
    """
    return bool(re.fullmatch(r"[A-Z][A-Z0-9-]{0,9}", s))


# ─────────────────────────────────────────────────────────────────────────────
# TradingView Recommend.All Score → Label Conversion
# ─────────────────────────────────────────────────────────────────────────────


def rec_score_to_label(score: float) -> str:
    """
    Convert TradingView Recommend.All float to canonical label.

    Score range: -1.0 (STRONG_SELL) to +1.0 (STRONG_BUY).

    Thresholds (match TradingView's own labeling):
      >= 0.5   → STRONG_BUY
      >= 0.1   → BUY
      > -0.1   → NEUTRAL
      > -0.5   → SELL
      else     → STRONG_SELL

    Parameters
    ----------
    score : float
        Raw Recommend.All score from screener

    Returns
    -------
    str
        Label: STRONG_BUY | BUY | NEUTRAL | SELL | STRONG_SELL
    """
    score = to_float(score, 0.0)
    if score >= 0.5:
        return "STRONG_BUY"
    if score >= 0.1:
        return "BUY"
    if score > -0.1:
        return "NEUTRAL"
    if score > -0.5:
        return "SELL"
    return "STRONG_SELL"
