def load_json_safe(path: Path, default: Any = None) -> Any:
    """
    Load JSON from file. Returns default on any error (missing file, parse error).

    Parameters
    ----------
    path : Path
        File path to load
    default : Any
        Value to return on error. Defaults to None.

    Returns
    -------
    Any
        Parsed JSON, or default if load fails.
    """
    if not path.exists():
        return default
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return default


def load_csv_safe(path: Path) -> pd.DataFrame:
    """
    Load CSV into DataFrame. Returns empty DataFrame on any error.

    Parameters
    ----------
    path : Path
        File path to load

    Returns
    -------
    pd.DataFrame
        Loaded data or empty DataFrame if load fails.
    """
    if not path.exists():
        return pd.DataFrame()
    try:
        return pd.read_csv(path)
    except Exception:
        return pd.DataFrame()


def write_json_safe(
    path: Path,
    data: Any,
    log_fn: Callable[[str, dict], None] | None = None,
) -> bool:
    """
    Write JSON to file atomically (via .tmp then rename).

    Parameters
    ----------
    path : Path
        File path to write to
    data : Any
        Data to serialize as JSON
    log_fn : Callable | None
        Logger function to call on error. Signature: log_fn(event_name, payload_dict)

    Returns
    -------
    bool
        True if write succeeded, False otherwise. Never raises.
    """
    # Ensure parent directories exist
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
    except Exception:
        if log_fn:
            log_fn("external_http_error", {"module": "write_json_safe", "error": "mkdir failed"})
        return False

    # Atomic write: write to .tmp, then rename
    tmp_path = path.with_suffix(path.suffix + ".tmp")
    try:
        json_str = json.dumps(data, indent=2, default=_json_default) + "\n"
        tmp_path.write_text(json_str, encoding="utf-8")
        os.rename(tmp_path, path)
        return True
    except Exception as e:
        # Clean up .tmp if it exists
        try:
            tmp_path.unlink()
        except Exception:
            pass
        if log_fn:
            log_fn("external_http_error", {"module": "write_json_safe", "error": str(e)[:300]})
        return False


def write_text_safe(
    path: Path,
    content: str,
    log_fn: Callable[[str, dict], None] | None = None,
) -> bool:
    """
    Write text to file atomically.

    Parameters
    ----------
    path : Path
        File path to write to
    content : str
        Text content
    log_fn : Callable | None
        Logger function to call on error

    Returns
    -------
    bool
        True if write succeeded, False otherwise. Never raises.
    """
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
    except Exception:
        if log_fn:
            log_fn("external_http_error", {"module": "write_text_safe", "error": "mkdir failed"})
        return False

    tmp_path = path.with_suffix(path.suffix + ".tmp")
    try:
        tmp_path.write_text(content, encoding="utf-8")
        os.rename(tmp_path, path)
        return True
    except Exception as e:
        try:
            tmp_path.unlink()
        except Exception:
            pass
        if log_fn:
            log_fn("external_http_error", {"module": "write_text_safe", "error": str(e)[:300]})
        return False


